create or replace function public.reviews_guard()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' and not public.is_admin() then
    new.status := 'pending';
    new.user_id := auth.uid();
    new.author := left(coalesce((select full_name from public.profiles where id = auth.uid()), ''), 60);
  end if;
  return new;
end $$;
drop trigger if exists reviews_guard on public.reviews;
create trigger reviews_guard before insert on public.reviews for each row execute function public.reviews_guard();

create or replace function public.reviews_rollup()
returns trigger language plpgsql security definer set search_path = public as $$
declare pid bigint := coalesce(new.product_id, old.product_id);
begin
  update public.products p set
    rating = coalesce((select round(avg(rating)::numeric, 2) from public.reviews where product_id = pid and status = 'approved'), 0),
    reviews_count = (select count(*) from public.reviews where product_id = pid and status = 'approved')
  where p.id = pid;
  return null;
end $$;
drop trigger if exists reviews_rollup on public.reviews;
create trigger reviews_rollup after insert or update or delete on public.reviews for each row execute function public.reviews_rollup();


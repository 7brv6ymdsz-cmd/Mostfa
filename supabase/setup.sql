create or replace function public.coupon_discount(p_code text, p_subtotal numeric, p_shipping numeric)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare c public.coupons; d numeric := 0;
begin
  select * into c from public.coupons where code = upper(trim(p_code));
  if not found or not c.active then return jsonb_build_object('ok', false, 'message', 'الكود غير صالح'); end if;
  if c.starts_at is not null and now() < c.starts_at then return jsonb_build_object('ok', false, 'message', 'الكود لسا ما بلّش'); end if;
  if c.ends_at is not null and now() > c.ends_at then return jsonb_build_object('ok', false, 'message', 'الكود منتهي'); end if;
  if c.max_uses is not null and c.uses >= c.max_uses then return jsonb_build_object('ok', false, 'message', 'الكود خلص'); end if;
  if p_subtotal < c.min_subtotal then
    return jsonb_build_object('ok', false, 'message', 'الحد الأدنى للطلب ' || c.min_subtotal::text, 'min', c.min_subtotal);
  end if;
  if c.kind = 'percent' then d := round(p_subtotal * least(c.value, 100) / 100, 2);
  elsif c.kind = 'fixed' then d := least(c.value, p_subtotal);
  else d := p_shipping; end if;
  return jsonb_build_object('ok', true, 'code', c.code, 'kind', c.kind, 'value', c.value, 'discount', d);
end $$;

create or replace function public.check_coupon(p_code text, p_subtotal numeric)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare s jsonb; ship numeric;
begin
  select data into s from public.settings where id = 1;
  ship := case when coalesce((s->'shipping'->>'freeOver')::numeric, 0) > 0 and p_subtotal >= (s->'shipping'->>'freeOver')::numeric then 0
               else coalesce((s->'shipping'->>'fee')::numeric, 0) end;
  return public.coupon_discount(p_code, p_subtotal, ship);
end $$;

-- =====================================================================
-- Orders: priced, validated and stock-checked on the server
-- =====================================================================
create or replace function public.place_order(p jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  s jsonb; it jsonb; prod public.products;
  items jsonb := '[]'::jsonb; sub numeric := 0; ship numeric; disc numeric := 0; cj jsonb;
  q int; oid text; m text := coalesce(p->>'method', 'cod'); c jsonb := p->'customer'; v_code text := nullif(upper(trim(coalesce(p->>'coupon', ''))), '');
  opts jsonb; o public.orders;
begin
  if c is null or char_length(trim(coalesce(c->>'name', ''))) < 2 then raise exception 'name_required'; end if;
  if char_length(regexp_replace(coalesce(c->>'phone', ''), '\D', '', 'g')) < 7 then raise exception 'phone_required'; end if;
  if char_length(trim(coalesce(c->>'city', ''))) < 1 or char_length(trim(coalesce(c->>'address', ''))) < 4 then raise exception 'address_required'; end if;
  if jsonb_typeof(p->'items') <> 'array' or jsonb_array_length(p->'items') = 0 or jsonb_array_length(p->'items') > 50 then raise exception 'items_invalid'; end if;

  select data into s from public.settings where id = 1;
  if not coalesce((s->'payments'->m->>'on')::boolean, m = 'cod') then raise exception 'method_unavailable'; end if;

  for it in select * from jsonb_array_elements(p->'items') loop
    q := greatest(1, least(50, coalesce((it->>'qty')::int, 1)));
    select * into prod from public.products where id = (it->>'id')::bigint and not hidden for update;
    if not found then raise exception 'product_unavailable:%', it->>'id'; end if;
    if prod.stock < q then raise exception 'out_of_stock:%', prod.name; end if;
    opts := case when jsonb_typeof(it->'options') = 'object' then it->'options' else '{}'::jsonb end;
    update public.products set stock = stock - q where id = prod.id;
    sub := sub + prod.price * q;
    items := items || jsonb_build_array(jsonb_build_object('id', prod.id, 'name', prod.name, 'price', prod.price, 'qty', q, 'options', opts,
      'image', coalesce(prod.images[1], '')));
  end loop;

  ship := case when coalesce((s->'shipping'->>'freeOver')::numeric, 0) > 0 and sub >= (s->'shipping'->>'freeOver')::numeric then 0
               else coalesce((s->'shipping'->>'fee')::numeric, 0) end;
  if v_code is not null then
    cj := public.coupon_discount(v_code, sub, ship);
    if not (cj->>'ok')::boolean then raise exception 'coupon_invalid:%', cj->>'message'; end if;
    disc := (cj->>'discount')::numeric;
    update public.coupons set uses = uses + 1 where coupons.code = v_code;
  end if;

  oid := 'R-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 7));
  insert into public.orders (id, user_id, customer, items, subtotal, discount, shipping, total, coupon, method, history)
  values (oid, auth.uid(),
    jsonb_build_object('name', left(trim(c->>'name'), 120), 'phone', left(regexp_replace(c->>'phone', '[^\d+]', '', 'g'), 40),
      'email', left(coalesce(c->>'email', ''), 160), 'city', left(trim(c->>'city'), 80), 'address', left(trim(c->>'address'), 300),
      'notes', left(coalesce(c->>'notes', ''), 500)),
    items, sub, disc, ship, greatest(0, sub - disc + ship), v_code, m,
    jsonb_build_array(jsonb_build_object('s', 'new', 't', now())))
  returning * into o;
  return to_jsonb(o) - 'note' - 'stock_applied';
end $$;

-- Guests can follow an order with its number and the phone used for it.
create or replace function public.track_order(p_id text, p_phone text)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare o public.orders; a text; b text;
begin
  select * into o from public.orders where id = upper(trim(p_id));
  if not found then return null; end if;
  a := right(regexp_replace(o.customer->>'phone', '\D', '', 'g'), 7);
  b := right(regexp_replace(coalesce(p_phone, ''), '\D', '', 'g'), 7);
  if char_length(b) < 7 or a <> b then return null; end if;
  return jsonb_build_object('id', o.id, 'status', o.status, 'paid', o.paid, 'method', o.method, 'items', o.items,
    'subtotal', o.subtotal, 'discount', o.discount, 'shipping', o.shipping, 'total', o.total,
    'created_at', o.created_at, 'history', o.history, 'city', o.customer->>'city');
end $$;

-- Admin: move an order through its statuses, giving stock back on cancel.
create or replace function public.admin_set_status(p_id text, p_status text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare o public.orders; it jsonb;
begin
  if not public.is_admin() then raise exception 'not_admin'; end if;
  if p_status not in ('new', 'confirmed', 'shipped', 'delivered', 'cancelled') then raise exception 'bad_status'; end if;
  select * into o from public.orders where id = p_id for update;
  if not found then raise exception 'not_found'; end if;
  if o.status = p_status then return to_jsonb(o); end if;
  if p_status = 'cancelled' and o.stock_applied then
    for it in select * from jsonb_array_elements(o.items) loop
      update public.products set stock = stock + (it->>'qty')::int where id = (it->>'id')::bigint;
    end loop;
    o.stock_applied := false;
  elsif p_status <> 'cancelled' and not o.stock_applied then
    for it in select * from jsonb_array_elements(o.items) loop
      update public.products set stock = greatest(0, stock - (it->>'qty')::int) where id = (it->>'id')::bigint;
    end loop;
    o.stock_applied := true;
  end if;
  update public.orders set status = p_status, stock_applied = o.stock_applied,
    paid = case when p_status = 'delivered' and method = 'cod' then true else paid end,
    history = history || jsonb_build_array(jsonb_build_object('s', p_status, 't', now()))
  where id = p_id returning * into o;
  return to_jsonb(o);
end $$;

-- =====================================================================
-- Reviews: only buyers of a delivered order, approved by the admin

-- can the caller see this conversation? (owner, holder of the guest token, or admin)
create or replace function public.conversation_access(p_id uuid, p_token text)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.conversations c where c.id = p_id
    and ((auth.uid() is not null and c.user_id = auth.uid()) or (coalesce(p_token, '') <> '' and c.token = p_token) or public.is_admin()));
$$;

create or replace function public.start_conversation(p jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_name text := left(trim(coalesce(p->>'name', '')), 80);
        v_contact text := left(trim(coalesce(p->>'contact', '')), 120);
        v_body text := trim(coalesce(p->>'body', ''));
        v_order text := nullif(upper(left(trim(coalesce(p->>'order_id', '')), 20)), '');
        v_product bigint := nullif(p->>'product_id', '')::bigint;
        c public.conversations;
begin
  if auth.uid() is not null and v_name = '' then select full_name into v_name from public.profiles where id = auth.uid(); end if;
  if auth.uid() is not null and v_contact = '' then select email into v_contact from auth.users where id = auth.uid(); end if;
  if char_length(v_name) < 2 then raise exception 'name_required'; end if;
  if auth.uid() is null and char_length(regexp_replace(v_contact, '\s', '', 'g')) < 6 then raise exception 'contact_required'; end if;
  if char_length(v_body) < 2 or char_length(v_body) > 2000 then raise exception 'message_length'; end if;
  -- simple flood guard: at most 5 new conversations from the same contact in 10 minutes
  if (select count(*) from public.conversations where contact = v_contact and created_at > now() - interval '10 minutes') >= 5 then raise exception 'too_many_messages'; end if;
  if v_product is not null and not exists (select 1 from public.products where id = v_product) then v_product := null; end if;
  insert into public.conversations (user_id, name, contact, subject, order_id, product_id, last_message)
  values (auth.uid(), v_name, v_contact, left(trim(coalesce(p->>'subject', '')), 120), v_order, v_product, left(v_body, 200))
  returning * into c;
  if jsonb_typeof(p->'bot') = 'array' then
    insert into public.conversation_messages (conversation_id, sender, body)
    select c.id, 'bot', left(x, 2000) from jsonb_array_elements_text(p->'bot') as x where char_length(trim(x)) > 0 limit 5;
  end if;
  insert into public.conversation_messages (conversation_id, sender, body) values (c.id, 'customer', v_body);
  return jsonb_build_object('id', c.id, 'token', c.token);
end $$;

create or replace function public.get_conversation(p_id uuid, p_token text default '')
returns jsonb language plpgsql security definer set search_path = public as $$
declare c public.conversations;
begin
  if not public.conversation_access(p_id, p_token) then return null; end if;
  select * into c from public.conversations where id = p_id;
  if not public.is_admin() and c.unread_customer then update public.conversations set unread_customer = false where id = p_id; end if;
  return jsonb_build_object('id', c.id, 'name', c.name, 'subject', c.subject, 'order_id', c.order_id, 'product_id', c.product_id,
    'status', c.status, 'created_at', c.created_at, 'updated_at', c.updated_at,
    'messages', coalesce((select jsonb_agg(jsonb_build_object('id', m.id, 'sender', m.sender, 'body', m.body, 'created_at', m.created_at) order by m.id)
                          from public.conversation_messages m where m.conversation_id = p_id), '[]'::jsonb));
end $$;

create or replace function public.reply_conversation(p_id uuid, p_token text, p_body text)
returns void language plpgsql security definer set search_path = public as $$
declare v text := trim(coalesce(p_body, ''));
begin
  if not public.conversation_access(p_id, p_token) then raise exception 'not_found'; end if;
  if char_length(v) < 1 or char_length(v) > 2000 then raise exception 'message_length'; end if;
  if (select count(*) from public.conversation_messages where conversation_id = p_id and sender = 'customer' and created_at > now() - interval '1 minute') >= 6 then raise exception 'too_many_messages'; end if;
  insert into public.conversation_messages (conversation_id, sender, body) values (p_id, 'customer', v);
  update public.conversations set status = 'open', unread_admin = true, last_message = left(v, 200) where id = p_id;
end $$;

create or replace function public.admin_reply(p_id uuid, p_body text)
returns void language plpgsql security definer set search_path = public as $$
declare v text := trim(coalesce(p_body, ''));
begin
  if not public.is_admin() then raise exception 'not_admin'; end if;
  if char_length(v) < 1 or char_length(v) > 2000 then raise exception 'message_length'; end if;
  insert into public.conversation_messages (conversation_id, sender, body) values (p_id, 'admin', v);
  update public.conversations set status = 'answered', unread_admin = false, unread_customer = true, last_message = left(v, 200) where id = p_id;
  if not found then raise exception 'not_found'; end if;
end $$;

create or replace function public.ask_question(p_product bigint, p_question text, p_name text default '')
returns void language plpgsql security definer set search_path = public as $$
declare q text := trim(coalesce(p_question, '')); n text := left(trim(coalesce(p_name, '')), 60);
begin
  if char_length(q) < 3 or char_length(q) > 500 then raise exception 'question_length'; end if;
  if not exists (select 1 from public.products where id = p_product and not hidden) then raise exception 'product_unavailable'; end if;
  if auth.uid() is not null and n = '' then select left(full_name, 60) into n from public.profiles where id = auth.uid(); end if;
  if (select count(*) from public.product_questions where product_id = p_product and created_at > now() - interval '1 minute') >= 10 then raise exception 'too_many_messages'; end if;
  insert into public.product_questions (product_id, user_id, author, question) values (p_product, auth.uid(), coalesce(nullif(n, ''), 'زائر'), q);
